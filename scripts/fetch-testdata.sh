# ---------------------------------------------------------------------------
# a64-tests: the AArch64 suite this repository *builds* rather than fetches
# ---------------------------------------------------------------------------
#
# Nothing is downloaded. There is no AArch64 corpus that can be used --
# SingleStepTests has no AArch64 repository, Arm's own architecture validation
# suite is licensed to implementers, sail-arm is a model rather than a corpus,
# and kvm-unit-tests is GPL-2.0 and is a machine gate rather than a core one.
# So the guests are ours (tests/a64/*.rs, MIT) and this builds them.
#
# The only tool needed is `rustc` with the aarch64-unknown-none target
# installed. That target's linker is `rust-lld`, which ships inside the Rust
# toolchain, so there is no C toolchain and no cross binutils anywhere in this
# path -- which is also why it can be in --all where riscv-arch-test cannot.
#
# src/cpu/arm/a64/conformance.rs is the runner, and says what each guest proves
# and where its expected values come from.
build_a64_tests() {
	need rustc

	local src="${REPO_ROOT}/tests/a64"
	local dest="${DEST_ROOT}/a64-tests"
	[ -d "$src" ] || die "${src} is missing; this is not an rsemu checkout"

	if ! rustc --print target-list 2>/dev/null | grep -qx aarch64-unknown-none; then
		die "this rustc does not know aarch64-unknown-none"
	fi
	# The precompiled `core` for the target. Without it every build below fails
	# with "can't find crate for core", which is a confusing way to say "run
	# rustup target add".
	if ! rustc --target aarch64-unknown-none --print target-libdir 2>/dev/null |
		xargs -r test -d; then
		die "the aarch64-unknown-none standard library is not installed
  rustup target add aarch64-unknown-none"
	fi

	mkdir -p "$dest"
	local guest name built=0
	for guest in "$src"/*.rs; do
		name="$(basename "$guest" .rs)"
		# rt.rs is `include!`d by every guest and is not one itself.
		[ "$name" = "rt" ] && continue
		if [ "$FORCE" != 1 ] && [ -f "${dest}/${name}.elf" ] &&
			[ "${dest}/${name}.elf" -nt "$guest" ] &&
			[ "${dest}/${name}.elf" -nt "${src}/rt.rs" ]; then
			note "  ${name}.elf is up to date"
			built=$((built + 1))
			continue
		fi
		note "  building ${name} ..."
		# -C panic=abort: there is no unwinder. -C debuginfo=0: the loader
		# reads program headers only, and debug sections would be megabytes of
		# nothing. The linker script pins the image at the board's DRAM base.
		rustc --edition 2024 \
			--target aarch64-unknown-none \
			-C panic=abort \
			-C opt-level=2 \
			-C debuginfo=0 \
			-C link-arg=-T -C link-arg="${src}/link.ld" \
			--crate-name "$name" \
			-o "${dest}/${name}.elf" \
			"$guest" || die "could not build ${name}"
		built=$((built + 1))
	done

	[ "$built" -gt 0 ] || die "no guests under ${src}"
	ok "a64-tests: ${built} guest binaries in ${dest}"
	note "    RSEMU_A64_TESTS=${dest} cargo test --all-features a64_conformance -- --nocapture"
}

# The level-3 guest binaries: statically linked Linux programs that
# `src/usermode/proof.rs` runs with no guest kernel under them.
#
# Built here rather than downloaded, for the same reason `a64-tests` is: the
# source is one file in this repository and a compiler's output does not belong
# in the tree. Everything comes out of the Rust toolchain -- the musl libc and
# its startup files ship with the target, and the linker is the rust-lld inside
# the toolchain -- so there is no C toolchain and no sysroot in this path.
#
# Every guest is built for every architecture the proof can run, because a
# second architecture is what proves the level-3 seam is not RISC-V-shaped
# (ROADMAP.md 2.1). A target whose standard library is not installed is skipped
# with a note rather than fatal: the proof runs whatever it finds.
build_usermode_guests() {
	need rustc

	local src="${REPO_ROOT}/tests/usermode"
	local dest="${DEST_ROOT}/usermode"
	[ -d "$src" ] || die "${src} is missing; this is not an rsemu checkout"

	# rustc drives the link through `cc` for musl targets, and this host's `cc`
	# is not a RISC-V one. rust-lld ships with the toolchain and is reached
	# through its `ld.lld` alias, because plain `rust-lld` refuses to guess
	# which flavour of linker it is being asked to be.
	local host ld
	host="$(rustc -vV | sed -n 's/^host: //p')"
	ld="$(rustc --print sysroot)/lib/rustlib/${host}/bin/gcc-ld/ld.lld"
	[ -x "$ld" ] || die "no rust-lld at ${ld}; install the llvm-tools component"

	mkdir -p "$dest"
	local pair target suffix guest name out built=0 targets=0
	for pair in riscv64gc-unknown-linux-musl:riscv64 aarch64-unknown-linux-musl:aarch64; do
		target="${pair%%:*}"
		suffix="${pair##*:}"
		if ! rustc --target "$target" --print target-libdir 2>/dev/null |
			xargs -r test -d; then
			note "  no ${target} standard library; skipping ${suffix}"
			note "    rustup target add ${target}"
			continue
		fi
		targets=$((targets + 1))
		for guest in "$src"/*.rs; do
			name="$(basename "$guest" .rs)"
			out="${dest}/${name}-${suffix}"
			if [ "$FORCE" != 1 ] && [ -f "$out" ] && [ "$out" -nt "$guest" ]; then
				note "  $(basename "$out") is up to date"
				built=$((built + 1))
				continue
			fi
			note "  building ${name} for ${target} ..."
			# -C debuginfo=0 -C strip=symbols: the loader reads program headers
			# and nothing else, and the debug sections are twenty times the
			# program.
			rustc --edition 2024 \
				--target "$target" \
				-C target-feature=+crt-static \
				-C link-self-contained=yes \
				-C linker="$ld" \
				-C linker-flavor=ld \
				-C opt-level=1 \
				-C debuginfo=0 \
				-C strip=symbols \
				--crate-name "$name" \
				-o "$out" \
				"$guest" || die "could not build ${name} for ${target}"
			built=$((built + 1))
		done
	done

	[ "$targets" -gt 0 ] || die "no usermode target installed
  rustup target add riscv64gc-unknown-linux-musl"
	[ "$built" -gt 0 ] || die "no guests under ${src}"
	ok "usermode-guests: ${built} static binaries in ${dest}"

	build_usermode_dynamic "$dest"

	note "    cargo test --all-features usermode::proof -- --nocapture"
}

# The dynamically linked guests.
#
# A static binary needs nothing but a compiler; a dynamic one needs a *dynamic
# loader*, and there is no way to build one of those out of a Rust toolchain.
# So this half is conditional in a way the static half is not: it looks for an
# `ld-linux-<arch>.so.1` on the host, and if there is not one it says so and
# leaves the corpus without a dynamic guest. `src/usermode/proof.rs` then skips
# the tests that need it, exactly as it skips an architecture whose standard
# library is not installed.
#
# Nothing is committed and nothing is downloaded here either: the loader is
# *copied* out of a cross sysroot the host already has, into the git-ignored
# corpus, and it is run as an emulated guest. glibc is LGPL, and running a
# program is ordinary use (CLAUDE.md, Provenance); shipping it here would not
# be, which is why this copies rather than vendors.
usermode_ldso() {
	local arch="$1" name="$2" candidate
	# The override names one file, so it only answers for the architecture
	# whose loader it is: a checkout with two cross sysroots must not be handed
	# an AArch64 ld.so when it asked for the RISC-V one.
	if [ -n "${RSEMU_USERMODE_LDSO:-}" ] &&
		[ -f "${RSEMU_USERMODE_LDSO}" ] &&
		[ "$(basename "${RSEMU_USERMODE_LDSO}")" = "$name" ]; then
		printf '%s\n' "${RSEMU_USERMODE_LDSO}"
		return 0
	fi
	for candidate in \
		"/usr/${arch}-unknown-linux-gnu/lib64/${name}" \
		"/usr/${arch}-unknown-linux-gnu/lib/${name}" \
		"/usr/${arch}-linux-gnu/lib64/${name}" \
		"/usr/${arch}-linux-gnu/lib/${name}" \
		"/lib/${name}" \
		"/lib64/${name}"; do
		[ -f "$candidate" ] && printf '%s\n' "$candidate" && return 0
	done
	return 1
}

build_usermode_dynamic() {
	local dest="$1"
	local src="${REPO_ROOT}/tests/usermode/dynamic"
	local host ld
	host="$(rustc -vV | sed -n 's/^host: //p')"
	ld="$(rustc --print sysroot)/lib/rustlib/${host}/bin/gcc-ld/ld.lld"

	local pair arch suffix target ldso ldso_name root built=0
	for pair in aarch64:aarch64:ld-linux-aarch64.so.1 \
		riscv64:riscv64gc:ld-linux-riscv64-lp64d.so.1; do
		arch="${pair%%:*}"
		suffix="${arch}"
		target="$(printf '%s' "$pair" | cut -d: -f2)-unknown-linux-gnu"
		ldso_name="${pair##*:}"
		if ! rustc --target "$target" --print target-libdir 2>/dev/null |
			xargs -r test -d; then
			note "  no ${target} standard library; skipping the ${suffix} dynamic guest"
			continue
		fi
		if ! ldso="$(usermode_ldso "$arch" "$ldso_name")"; then
			note "  no ${ldso_name} on this host; skipping the ${suffix} dynamic guest"
			note "    a cross sysroot supplies one, or set RSEMU_USERMODE_LDSO"
			continue
		fi
		root="${dest}/dynamic-${suffix}.root"
		mkdir -p "${root}/lib"
		note "  building dynamic for ${target} against ${ldso} ..."
		# `-nostdlib`: the guest links no libc, so the loader is the only
		# thing between the auxiliary vector and `_start`. `-soname` because a
		# DT_NEEDED is a name and the file's own is not consulted.
		rustc --edition 2024 --target "$target" \
			--crate-type cdylib \
			-C linker="$ld" -C linker-flavor=ld \
			-C link-arg=-nostdlib -C link-arg="-soname=libgreet.so" \
			-C panic=abort -C opt-level=1 -C debuginfo=0 -C strip=symbols \
			--crate-name greet -o "${root}/lib/libgreet.so" "${src}/lib.rs" ||
			die "could not build the ${suffix} shared object"
		rustc --edition 2024 --target "$target" \
			-C linker="$ld" -C linker-flavor=ld \
			-C link-arg=-nostdlib -C link-arg=-pie \
			-C link-arg="--dynamic-linker=/lib/${ldso_name}" \
			-C link-arg="-L${root}/lib" -C link-arg=-lgreet \
			-C panic=abort -C opt-level=1 -C debuginfo=0 -C strip=symbols \
			--crate-name dynamic -o "${dest}/dynamic-${suffix}" "${src}/main.rs" ||
			die "could not build the ${suffix} dynamic executable"
		cp -f "$ldso" "${root}/lib/${ldso_name}"
		built=$((built + 1))

		build_usermode_glibc "$dest" "$suffix" "$ldso" "$ldso_name" || true
	done

	if [ "$built" -gt 0 ]; then
		ok "usermode-guests: ${built} dynamically linked guest(s) in ${dest}"
	else
		note "usermode-guests: no dynamic loader on this host, so no dynamic guest"
	fi
}

# The *whole* dynamically linked program: `tests/usermode/hello.rs` again, but
# linked against the host's cross glibc rather than statically against musl.
#
# This one is a ledger entry rather than a gate, and it needs a cross `gcc` as
# a link driver because a glibc executable pulls in `Scrt1.o`, `crti.o` and
# `libgcc_s`. Absent either, it is skipped. `src/usermode/proof.rs` says what
# it measures.
build_usermode_glibc() {
	local dest="$1" suffix="$2" ldso="$3" ldso_name="$4"
	local triple="${suffix}-unknown-linux-gnu" cc root libc libgcc
	cc="${triple}-gcc"
	command -v "$cc" >/dev/null 2>&1 || {
		note "  no ${cc}; skipping the ${suffix} glibc guest"
		return 1
	}
	libc="$("$cc" -print-file-name=libc.so.6)"
	libgcc="$("$cc" -print-file-name=libgcc_s.so.1)"
	[ -f "$libc" ] || return 1
	root="${dest}/glibc-${suffix}.root"
	mkdir -p "${root}/lib"
	note "  building glibc for ${triple} ..."
	rustc --edition 2024 --target "$triple" \
		-C linker="$cc" -C opt-level=1 -C debuginfo=0 -C strip=symbols \
		--crate-name glibc -o "${dest}/glibc-${suffix}" \
		"${REPO_ROOT}/tests/usermode/hello.rs" || return 1
	cp -f "$ldso" "${root}/lib/${ldso_name}"
	cp -f "$libc" "${root}/lib/libc.so.6"
	# `libgcc_s` is a DT_NEEDED of anything rustc links, and it lives in the
	# compiler's directory rather than the sysroot.
	if [ -f "$libgcc" ]; then
		cp -f "$libgcc" "${root}/lib/libgcc_s.so.1"
	fi
	return 0
}

